#!/usr/bin/env python3
"""Records the app's voice clips: every sentence the app can say, in the tutorial's neural voices (app-voice.js reads them).

Usage:  python3 tools/app-voice/build.py           # records sentences that have no clip yet, removes clips nothing says any more
        python3 tools/app-voice/build.py --news    # only version.json's news (scripts/release.sh runs this after the bump); removes nothing
        python3 tools/app-voice/build.py --all     # records everything again (after changing a voice in app-voice.js VOICES)
Needs:  pip install --user edge-tts   (Microsoft's neural voices; the clips are committed, so the app needs nothing at runtime)

The sentences come from tools/app-voice/phrases.cjs (it reads them from the code that speaks them) and each clip's id from
app-voice.js idOf() (hash of voice + sentence), both via node, so the app, the clips and the tests can never disagree.
Writes app-voice/<lang>/<id>.mp3 and app-voice-data.js ({voices, clips:{lang:{id: length ms}}}). tests/app-voice.test.cjs fails
when a sentence the app says has no clip.
"""
import asyncio, json, os, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT = os.path.join(ROOT, 'app-voice')
DATA = os.path.join(ROOT, 'app-voice-data.js')


def plan(news_only):
    js = ("const V=require('./app-voice.js'),P=require('./tools/app-voice/phrases.cjs');"
          "const h=P.harvest(%s),out=[];for(const l of Object.keys(h.out))for(const s of h.out[l])out.push({lang:l,s,id:V.idOf(l,s)});"
          "process.stdout.write(JSON.stringify({voices:V.VOICES,plan:out,sources:h.src}))") % ('true' if news_only else 'false')
    return json.loads(subprocess.check_output(['node', '-e', js], cwd=ROOT))


def load_old():
    if not os.path.exists(DATA):
        return {}
    js = "global.window=undefined;const d=require('./app-voice-data.js');process.stdout.write(JSON.stringify(d.clips||{}))"
    try:
        return json.loads(subprocess.check_output(['node', '-e', js], cwd=ROOT))
    except Exception:
        return {}


async def record(voice, text, path):
    import edge_tts
    for attempt in range(5):
        try:
            audio = bytearray()
            async for ch in edge_tts.Communicate(text, voice).stream():
                if ch['type'] == 'audio':
                    audio.extend(ch['data'])
            if not audio:
                raise RuntimeError('no audio')
            tmp = path + '.part'
            with open(tmp, 'wb') as f:
                f.write(audio)
            os.replace(tmp, path)
            return
        except Exception:
            if attempt == 4:
                raise
            await asyncio.sleep(2 + attempt * 3)


def duration_ms(path):
    try:
        o = subprocess.check_output(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', path])
        return round(float(o.strip()) * 1000)
    except Exception:
        return 1


def write_data(voices, clips):
    body = {'voices': voices, 'clips': {l: dict(sorted(clips[l].items())) for l in sorted(clips)}}
    js = ('/* app-voice-data.js: GENERATED by tools/app-voice/build.py, do not edit by hand. The app\'s recorded voice (app-voice.js):\n'
          '   per language, clip id (app-voice.js idOf: hash of voice + sentence) -> length in ms; the clip is app-voice/<lang>/<id>.mp3. */\n'
          '(function (root) {\n    const DATA = ' + json.dumps(body, separators=(',', ':')) + ';\n'
          "    if (typeof module === 'object' && module.exports) module.exports = DATA;\n"
          '    if (root) root.LowiAppVoiceData = DATA;\n'
          "})(typeof window !== 'undefined' ? window : null);\n")
    with open(DATA, 'w', encoding='utf-8') as f:
        f.write(js)


async def main():
    news_only, every = '--news' in sys.argv, '--all' in sys.argv
    p = plan(news_only)
    voices, old = p['voices'], load_old()
    clips = {l: dict(m) for l, m in old.items()} if news_only else {}
    todo, kept = [], 0
    for item in p['plan']:
        lang, text, cid = item['lang'], item['s'], item['id']
        path = os.path.join(OUT, lang, cid + '.mp3')
        os.makedirs(os.path.dirname(path), exist_ok=True)
        if not every and os.path.exists(path) and os.path.getsize(path) > 0:
            clips.setdefault(lang, {})[cid] = old.get(lang, {}).get(cid) or duration_ms(path)
            kept += 1
            continue
        todo.append((lang, text, voices[lang], cid, path))
    sem = asyncio.Semaphore(6)
    done = [0]

    async def one(lang, text, voice, cid, path):
        async with sem:
            await record(voice, text, path)
        clips.setdefault(lang, {})[cid] = duration_ms(path)
        done[0] += 1
        if done[0] % 25 == 0:
            print('recorded %d/%d' % (done[0], len(todo)), flush=True)
            write_data(voices, clips)  # progress survives an interruption
    await asyncio.gather(*(one(*t) for t in todo))
    if not news_only:
        used = {(l, c + '.mp3') for l, m in clips.items() for c in m}
        for lang in os.listdir(OUT) if os.path.isdir(OUT) else []:
            d = os.path.join(OUT, lang)
            if not os.path.isdir(d):
                continue
            for f in os.listdir(d):
                if (lang, f) not in used:
                    os.remove(os.path.join(d, f))
                    print('removed', lang, f)
    write_data(voices, clips)
    print('app voice clips: %d recorded, %d unchanged; sentences per source %s' % (len(todo), kept, json.dumps(p['sources'])))


if __name__ == '__main__':
    asyncio.run(main())
