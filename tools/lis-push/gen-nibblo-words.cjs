#!/usr/bin/env node
/* Writes supabase/functions/n1-push/nibblo-words.ts from nibblo-core.js (the one place Nibblo's menu lives), so a
 * Nibblo meal notification names the dish in the phone's own language (EN/DE/ES), exactly as Chat and For You do.
 * Usage: node tools/lis-push/gen-nibblo-words.cjs [--check]   (--check: exit 1 when the committed file is not what this writes)
 * Run it again whenever MENU in nibblo-core.js changes (tests/nibblo-push.test.cjs checks the two are in sync). */
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..', '..');
const N = require(path.join(root, 'nibblo-core.js'));
const OUT = path.join(root, 'supabase', 'functions', 'n1-push', 'nibblo-words.ts');

function build() {
  const dishes = {};
  for (const s of Object.keys(N.MENU)) for (const d of N.MENU[s]) dishes[N.bookId(d.r)] = { e: d.e, n: d.name.slice(0, 3) };
  const L = [];
  L.push('/* GENERATED by tools/lis-push/gen-nibblo-words.cjs from nibblo-core.js. Do not edit by hand. */');
  L.push('/* Nibblo\'s account and every dish it posts: Recipe Book id -> emoji and the name in [en, de, es]. */');
  L.push('export const NB_UID = ' + JSON.stringify(N.UID) + ';');
  L.push('export const NB_NAME = ' + JSON.stringify(N.NAME) + ';');
  L.push('export const NB_DISHES: Record<string, { e: string; n: [string, string, string] }> = {');
  for (const k of Object.keys(dishes).sort()) L.push('  ' + JSON.stringify(k) + ': ' + JSON.stringify(dishes[k]) + ',');
  L.push('};');
  return L.join('\n') + '\n';
}
module.exports = { build, OUT };

if (require.main === module) {
  const s = build();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== s) { console.error('nibblo-words.ts is out of date: run node tools/lis-push/gen-nibblo-words.cjs'); process.exit(1); }
    console.log('nibblo-words.ts is up to date');
  } else { fs.writeFileSync(OUT, s); console.log('wrote ' + path.relative(root, OUT)); }
}
