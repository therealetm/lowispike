#!/usr/bin/env node
/* Writes supabase/proposals/nibblo_meals_20261025.sql from nibblo-core.js (the one place the menu and the texts live).
 * Usage: node tools/nibblo/gen-sql.cjs [--check]   (--check: exit 1 when the committed file is not what this would write) */
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..', '..');
const N = require(path.join(root, 'nibblo-core.js'));
const K = require(path.join(root, 'community-chat-core.js'));
const OUT = path.join(root, 'supabase', 'proposals', 'nibblo_meals_20261025.sql');

const q = s => "'" + String(s).replace(/'/g, "''") + "'";
function build() {
  const L = [];
  L.push('-- LOWiSPIKE inspiration bot "Nibblo": a Recipe Book meal in the main Chat and in For You at 07:30, 12:30 and 18:30 Europe/Berlin.');
  L.push('-- GENERATED by tools/nibblo/gen-sql.cjs from nibblo-core.js. Do not edit by hand; tests/nibblo-core.test.cjs checks it.');
  L.push('-- Safe to run again: every step is an upsert or "if not exists", and each post is written once (nibblo_log), even if it is later deleted.');
  L.push('begin;');
  L.push('');
  L.push('-- 1. The bot account. "@bot.lowispike.invalid" now also marks an account as a bot (profiles.bot), next to the old crowd/gate-test addresses.');
  L.push("create or replace function public.lowi_is_bot(uid uuid) returns boolean language sql stable security definer set search_path to '' as $f$select coalesce((select u.email like 'crowd%@crowd.lowispike.invalid' or u.email like 'lowispike.gatetest+%@gmail.com' or u.email like '%@bot.lowispike.invalid' from auth.users u where u.id=uid),false)$f$;");
  L.push('insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token, email_change_token_new, email_change, email_change_token_current, phone_change, phone_change_token, reauthentication_token, is_sso_user, is_anonymous)');
  L.push("  values ('00000000-0000-0000-0000-000000000000', " + q(N.UID) + ", 'authenticated', 'authenticated', " + q(N.EMAIL) + ", '', now(), '{\"provider\":\"email\",\"providers\":[\"email\"]}', '{\"name\":\"Nibblo\",\"lowi_bot\":\"inspiration\"}', now(), now(), '', '', '', '', '', '', '', '', false, false)");
  L.push('  on conflict (id) do nothing;');
  L.push('-- (no password: nobody can sign in as the bot; only this database function writes for it)');
  L.push('insert into public.profiles (id, name, look, lv) values (' + q(N.UID) + ', ' + q(N.NAME) + ', ' + q(N.LOOK) + ', 2)');
  L.push('  on conflict (id) do update set name = excluded.name, look = excluded.look;');
  L.push('');
  L.push('-- 2. What it posts. Only the English text lives here: each phone shows the dish and caption in its own language (nibblo-core.js).');
  L.push('create table if not exists public.nibblo_menu (slot text not null, idx int not null, rec text not null, emoji text not null, name_en text not null, line_en text not null, photo text not null, head text not null, primary key (slot, idx));');
  L.push('create table if not exists public.nibblo_intro (slot text not null, idx int not null, en text not null, primary key (slot, idx));');
  L.push('create table if not exists public.nibblo_log (id text primary key, posted_at timestamptz not null default now());');
  L.push('alter table public.nibblo_menu enable row level security; alter table public.nibblo_intro enable row level security; alter table public.nibblo_log enable row level security;');
  L.push('revoke all on public.nibblo_menu, public.nibblo_intro, public.nibblo_log from anon, authenticated;');
  L.push('delete from public.nibblo_menu; delete from public.nibblo_intro;');
  for (const s of Object.keys(N.SLOTS)) {
    N.MENU[s].forEach((d, i) => {
      const url = N.photoUrl(d.r), head = K.mealBody(url, d.name[0], 'low', '');
      if (!head) throw new Error('mealBody refused ' + d.r);
      L.push('insert into public.nibblo_menu values (' + [q(s), i, q(N.bookId(d.r)), q(d.e), q(d.name[0]), q(d.line[0]), q(url), q(head)].join(', ') + ');');
    });
    N.INTROS[s].forEach((t, i) => L.push('insert into public.nibblo_intro values (' + [q(s), i, q(t[0])].join(', ') + ');'));
  }
  L.push('');
  L.push('-- 3. One post: the chat message (id nb-YYYYMMDD-slot) and the same meal in For You (id s + message id), like a member sharing a logged meal.');
  L.push('--    The dish and intro are chosen by (day number since 1 Jan 2026) mod count, the same rule as nibblo-core.js pick().');
  L.push("create or replace function public.nibblo_post(p_day date, p_slot text, p_at timestamptz default now()) returns text language plpgsql security definer set search_path to '' as $f$");
  L.push('declare dn int := p_day - date \'2026-01-01\'; nm int; ni int; m record; i record; mid text := \'nb-\' || to_char(p_day, \'YYYYMMDD\') || \'-\' || p_slot; k int;');
  L.push('begin');
  L.push("  if p_slot not in ('m', 'n', 'e') then return null; end if;");
  L.push('  insert into public.nibblo_log (id, posted_at) values (mid, p_at) on conflict (id) do nothing;');
  L.push('  get diagnostics k = row_count; if k = 0 then return null; end if;');
  L.push('  select count(*) into nm from public.nibblo_menu where slot = p_slot; select count(*) into ni from public.nibblo_intro where slot = p_slot;');
  L.push('  if nm = 0 or ni = 0 then raise exception \'nibblo: empty menu for %\', p_slot; end if;');
  L.push('  select * into m from public.nibblo_menu where slot = p_slot and idx = ((dn % nm) + nm) % nm;');
  L.push('  select * into i from public.nibblo_intro where slot = p_slot and idx = ((dn % ni) + ni) % ni;');
  L.push("  insert into public.messages (id, room, user_id, who, body, created_at) values (mid, 'all', " + q(N.UID) + "::uuid, " + q(N.NAME) + ", m.head || ' ' || i.en || ' ' || m.line_en, p_at) on conflict (id) do nothing;");
  L.push("  insert into public.posts (id, user_id, who, cap, photo_url, rec, lv, meta, created_at) values ('s' || mid, " + q(N.UID) + "::uuid, " + q(N.NAME) + ", i.en || ' ' || m.emoji || ' ' || m.name_en || '. ' || m.line_en, m.photo, m.rec, 2,");
  L.push("    jsonb_build_object('dish', m.name_en, 'from', 'community', 'spike', 'low', 'nb', jsonb_build_object('d', to_char(p_day, 'YYYYMMDD'), 's', p_slot)), p_at) on conflict (id) do nothing;");
  L.push('  return mid;');
  L.push('end $f$;');
  L.push('');
  L.push('-- 4. The clock: every 5 minutes; a slot posts from its Berlin time for ' + N.WINDOW_MIN + ' minutes, once. Berlin time, so summer/winter time needs nothing.');
  const cond = Object.keys(N.SLOTS).map(s => "when t >= time '" + N.SLOTS[s] + "' and t < time '" + N.SLOTS[s] + "' + interval '" + N.WINDOW_MIN + " minutes' then '" + s + "'").join(' ');
  L.push("create or replace function public.nibblo_tick(p_now timestamptz default now()) returns text language plpgsql security definer set search_path to '' as $f$");
  L.push("declare l timestamp := p_now at time zone '" + N.TZ + "'; t time := l::time; s text;");
  L.push('begin');
  L.push('  s := case ' + cond + ' end;');
  L.push('  if s is null then return null; end if;');
  L.push('  return public.nibblo_post(l::date, s, p_now);');
  L.push('end $f$;');
  L.push('revoke execute on function public.nibblo_post(date, text, timestamptz), public.nibblo_tick(timestamptz) from public, anon, authenticated;');
  L.push("select cron.unschedule(jobid) from cron.job where jobname = 'nibblo-meals';");
  L.push("select cron.schedule('nibblo-meals', '*/5 * * * *', 'select public.nibblo_tick()');");
  L.push('commit;');
  return L.join('\n') + '\n';
}

if (require.main === module) {
  const sql = build();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== sql) { console.error('nibblo SQL is out of date: run node tools/nibblo/gen-sql.cjs'); process.exit(1); }
    console.log('nibblo SQL up to date');
  } else { fs.writeFileSync(OUT, sql); console.log('wrote ' + path.relative(root, OUT)); }
}
module.exports = { build, OUT };
